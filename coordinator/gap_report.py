"""Build reports/gap_report.md from the JSONL audit traces in logs/ (nothing is hand-written:
every row below is read from a logged agent turn)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def main(log_dir: Path = ROOT / "logs", out: Path = ROOT / "reports" / "gap_report.md") -> int:
    gaps = yaml.safe_load((ROOT / "coordinator" / "gaps.yaml").read_text())
    status = json.loads((ROOT / "kb" / "fetch_status.json").read_text())
    runs, turns = [], []
    for p in sorted(log_dir.glob("*.jsonl")):
        for line in p.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            if r["type"] == "run_summary":
                runs.append(r)
            elif r["type"] == "agent_turn" and r.get("gap"):
                turns.append(r)
    L = ["# CareGuard gap report", "",
         "Generated by `coordinator/gap_report.py` from the audit traces in `logs/`. Each gap below was raised by an agent "
         "turn during a scenario run; the UAE and global evidence columns are the chunks the agent actually retrieved "
         "(document, page, BM25 score).", "", "## Runs", "",
         "| Scenario | Run id | Backend | Retriever | Expected rules fired | Citation checks | Grounded turns | Gaps |",
         "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        L.append(f"| {r['scenario']} | `{r['run_id']}` | {r['backend']} | {r['retriever']} | {r['expected_rules_fired']} | "
                 f"{r['citation_accuracy']} | {r['grounded_turns']} | {', '.join(r['gaps_found'])} |")
    L += ["", "## Gaps", ""]
    for gid, g in gaps.items():
        hits = [t for t in turns if t["gap"] == gid]
        if not hits:
            continue
        L += [f"### {gid}. {g['title']}", ""]
        for t in hits:
            scen = t["run_id"].split("-")[0]
            uae = t["retrieved"][0] if t["retrieved"] else None
            uae_txt = (f"{uae['doc_id']} p.{uae['page']} (score {uae['score']}, "
                       f"{'above' if t['supported'] else 'below'} support threshold {t['support_threshold']})") if uae else "nothing retrieved"
            L += [f"- Raised by **{t['agent']}** (`{t['rule_id']}`) in {scen} at {t['sim_time']}.",
                  f"  - Agent decision: {t['decision']}",
                  f"  - Closest UAE text retrieved: {uae_txt}."]
            for h in t.get("retrieved_global", []):
                L.append(f"  - Global example retrieved: {h['doc_id']} p.{h['page']} (score {h['score']}): \"{h['excerpt'][:160].strip()}...\"")
        L += [f"- Global example (catalogue): {g['global_example']}", f"- Recommendation: {g['recommendation']}", ""]
    pend = {k: v for k, v in status.items() if v["status"] != "fetched"}
    L += ["## Knowledge-base coverage gaps", "",
          "Documents listed in `kb/manifest.yaml` that are not in the KB, so no agent could retrieve them:", ""]
    for k, v in pend.items():
        L.append(f"- `{k}` ({v['status']}): {v['title']} <{v['url']}>")
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
